// Generates src/lib/hijriTables.ts from full ICU (Node) so the app never depends on the device's (possibly trimmed)
// ICU calendar data. For each calendar and Hijri year we store the epoch day (days since 1970-01-01 UTC) of 1 Muharram
// and a 12-bit mask of 30-day months (bit i = month i+1 has 30 days).
// Run: node scripts/generate-hijri-tables.mjs
import { writeFileSync } from "node:fs";
const FIRST = 1340, LAST = 1520;
const DAY = 86400000;
function table(cal) {
  const f = new Intl.DateTimeFormat("en-u-ca-" + cal, { timeZone: "UTC", day: "numeric", month: "numeric", year: "numeric" });
  if (f.resolvedOptions().calendar !== cal) throw new Error("ICU lacks " + cal);
  const starts = new Map(); // "y-m" -> epoch day
  const from = Math.floor(Date.UTC(1921, 0, 1) / DAY), to = Math.floor(Date.UTC(2098, 11, 31) / DAY);
  for (let e = from; e <= to; e++) {
    const p = f.formatToParts(new Date(e * DAY + DAY / 2));
    const g = (t) => Number(p.find((x) => x.type === t).value);
    if (g("day") === 1) starts.set(`${g("year")}-${g("month")}`, e);
  }
  const rows = [];
  for (let y = FIRST; y <= LAST; y++) {
    let mask = 0;
    for (let m = 1; m <= 12; m++) {
      const a = starts.get(`${y}-${m}`), b = m < 12 ? starts.get(`${y}-${m + 1}`) : starts.get(`${y + 1}-1`);
      if (a === undefined || b === undefined) throw new Error(`${cal} missing ${y}-${m}`);
      const len = b - a; if (len !== 29 && len !== 30) throw new Error(`${cal} ${y}-${m} len ${len}`);
      if (len === 30) mask |= 1 << (m - 1);
    }
    rows.push([starts.get(`${y}-1`), mask]);
  }
  return rows;
}
const ua = table("islamic-umalqura"), ast = table("islamic");
const fmt = (rows) => "[" + rows.map(([s, m]) => `${s},${m}`).join(",") + "]";
writeFileSync(new URL("../src/lib/hijriTables.ts", import.meta.url), `// GENERATED by scripts/generate-hijri-tables.mjs from ICU ${process.versions.icu} (Node ${process.version}). Do not edit.
// Per Hijri year ${FIRST}–${LAST}: [epoch day of 1 Muharram, 12-bit mask of 30-day months], flattened.
export const HIJRI_TABLE_FIRST_YEAR = ${FIRST};
export const HIJRI_TABLE_LAST_YEAR = ${LAST};
export const UMALQURA_TABLE: readonly number[] = ${fmt(ua)};
export const ASTRONOMICAL_TABLE: readonly number[] = ${fmt(ast)};
`);
console.log("wrote", ua.length, "years per table");
